// Builds standalone/jarvis.html: the complete JARVIS (kernel, skills, HUD,
// voice, learning, privacy) in one self-contained HTML file. No server needed.
//   npm run build:standalone
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const at = (...p) => join(root, ...p);
const pkg = JSON.parse(readFileSync(at('package.json'), 'utf8'));

const swap = {
  name: 'jarvis-standalone',
  setup(b) {
    // Node built-ins become small browser shims.
    b.onResolve({ filter: /^node:(events|crypto|fs|path)$/ }, (args) => ({ path: at('src/browser/shims', `${args.path.slice(5)}.js`) }));
    // File storage becomes browser storage.
    b.onResolve({ filter: /memory\/store\.js$/ }, (args) => (args.importer.includes(`${root}/src/`) ? { path: at('src/browser/store.js') } : undefined));
    // HTTP calls from the dashboard become in-page calls.
    b.onResolve({ filter: /^\.\/api\.js$/ }, (args) => (args.importer.includes(`${root}/public/js/`) ? { path: at('src/browser/api.js') } : undefined));
  },
};

const result = await build({
  entryPoints: [at('src/browser/entry.js')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['chrome111', 'edge111', 'firefox115', 'safari16.4'],
  minify: true,
  legalComments: 'none',
  write: false,
  plugins: [swap],
  define: { 'process.env.NODE_ENV': '"production"' },
  // Shared modules read optional settings from process.env; in a page there are none.
  banner: { js: 'globalThis.process ??= { env: {} };' },
  logLevel: 'warning',
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');

// Inline the stylesheets, with fonts embedded as data URIs.
let css = `${readFileSync(at('public/styles.css'), 'utf8')}\n${readFileSync(at('public/hud.css'), 'utf8')}`;
css = css.replace(/url\("\/fonts\/([^"]+\.woff2)"\)/g, (_, file) => `url("data:font/woff2;base64,${readFileSync(at('public/fonts', file)).toString('base64')}")`);
const favicon = `data:image/svg+xml;base64,${readFileSync(at('public/favicon.svg')).toString('base64')}`;

let html = readFileSync(at('public/index.html'), 'utf8');
const replace = (from, to) => {
  if (!html.includes(from)) throw new Error(`build: marker not found: ${from}`);
  html = html.replace(from, () => to);
};
replace('<link rel="icon" href="/favicon.svg" type="image/svg+xml">', `<link rel="icon" href="${favicon}" type="image/svg+xml">`);
replace('<link rel="stylesheet" href="/styles.css">\n  <link rel="stylesheet" href="/hud.css">', `<style>\n${css}\n</style>`);
replace('<script type="module" src="/js/main.js"></script>', `<script type="module">\n${js}\n</script>`);
replace('<!doctype html>', `<!doctype html>\n<!-- JARVIS ${pkg.version}, standalone build. Generated by scripts/build-standalone.mjs from the jarvis/ sources; edit those, not this file.\n     Fonts: Rajdhani and Orbitron, SIL Open Font License 1.1. -->`);

mkdirSync(at('standalone'), { recursive: true });
writeFileSync(at('standalone/jarvis.html'), html);
console.log(`standalone/jarvis.html  ${(html.length / 1024).toFixed(0)} KB (script ${(js.length / 1024).toFixed(0)} KB)`);
